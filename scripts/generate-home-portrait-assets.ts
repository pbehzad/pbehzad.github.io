/**
 * Generates the static assets for the home portrait's glass form.
 *
 * npm run generate:home-portrait
 *
 * 1. A displacement map for the refracting rim. Inside a band along the
 *    organic outline, red and green encode an inward sample offset that grows
 *    toward the edge, so the photo reads as magnified and compressed through
 *    a thick liquid edge while the centre stays undistorted.
 * 2. The faint ASCII trace behind the form: the photo's own luminance,
 *    sampled on a character grid through the same crop, quantized to a short
 *    ramp.
 *
 * Output: src/app/ui/homePortraitAssets.ts. Nothing is computed at runtime.
 * `sharp` is provided by Next.js for image optimization.
 */

import fs from 'fs';
import path from 'path';
import sharp from 'sharp';
import { encodeRgbPng, toPngDataUri } from './lib/png';
import { samplePortraitOutline } from '../src/app/ui/portraitShape';
import {
  PHOTO_BOX,
  PHOTO_SOURCE_SIZE,
  RIM_DEPTH,
  TRACE_BOX,
  TRACE_COLUMNS,
  TRACE_LINE_HEIGHT,
  TRACE_ROWS,
  VIEW_HEIGHT,
  VIEW_WIDTH,
} from '../src/app/ui/homePortraitGeometry';

const MAP_SCALE = 4; // view-box units per map pixel
const RIM_EXPONENT = 1.7;
const TRACE_RAMP = ' .:c';
const PHOTO_FILE = path.join(process.cwd(), 'public', 'ParhamBehzad-display.jpg');

type Point = readonly [number, number];

function buildDisplacementMap(): string {
  const outline: Point[] = samplePortraitOutline(48).map(([x, y]) => [x * VIEW_WIDTH, y * VIEW_HEIGHT]);
  const width = Math.round(VIEW_WIDTH / MAP_SCALE);
  const height = Math.round(VIEW_HEIGHT / MAP_SCALE);
  const pixels = new Uint8Array(width * height * 3);

  for (let py = 0; py < height; py++) {
    for (let px = 0; px < width; px++) {
      const x = (px + 0.5) * MAP_SCALE;
      const y = (py + 0.5) * MAP_SCALE;

      // Nearest point on the outline, and inside test by ray casting.
      let best = Infinity;
      let nx = 0;
      let ny = 0;
      let inside = false;
      for (let i = 0, j = outline.length - 1; i < outline.length; j = i++) {
        const [ax, ay] = outline[j];
        const [bx, by] = outline[i];
        const dx = bx - ax;
        const dy = by - ay;
        const t = Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)));
        const cx = ax + t * dx;
        const cy = ay + t * dy;
        const distance = Math.hypot(x - cx, y - cy);
        if (distance < best) {
          best = distance;
          nx = cx;
          ny = cy;
        }
        if ((ay > y) !== (by > y) && x < ((bx - ax) * (y - ay)) / (by - ay) + ax) inside = !inside;
      }

      let offsetX = 0;
      let offsetY = 0;
      if (inside && best < RIM_DEPTH && best > 0) {
        // Toward the centre: away from the nearest outline point.
        const strength = (1 - best / RIM_DEPTH) ** RIM_EXPONENT;
        offsetX = ((x - nx) / best) * strength;
        offsetY = ((y - ny) / best) * strength;
      }
      const i = (py * width + px) * 3;
      pixels[i] = Math.round((0.5 + offsetX * 0.5) * 255);
      pixels[i + 1] = Math.round((0.5 + offsetY * 0.5) * 255);
      pixels[i + 2] = 128;
    }
  }
  return toPngDataUri(encodeRgbPng(width, height, pixels));
}

async function buildTrace(): Promise<string[]> {
  const SAMPLE = 600;
  const { data } = await sharp(PHOTO_FILE)
    .greyscale()
    .resize(SAMPLE, SAMPLE)
    .raw()
    .toBuffer({ resolveWithObject: true });

  const fieldWidth = TRACE_BOX.width * VIEW_WIDTH;
  const cell = fieldWidth / TRACE_COLUMNS; // view-box units per column
  const rowHeight = (cell / 0.6) * TRACE_LINE_HEIGHT;
  const left = TRACE_BOX.left * VIEW_WIDTH;
  const top = TRACE_BOX.top * VIEW_HEIGHT;

  const rows: string[] = [];
  for (let row = 0; row < TRACE_ROWS; row++) {
    let line = '';
    for (let column = 0; column < TRACE_COLUMNS; column++) {
      const x = left + (column + 0.5) * cell;
      const y = top + (row + 0.5) * rowHeight;
      const u = (x - PHOTO_BOX.x) / PHOTO_BOX.size;
      const v = (y - PHOTO_BOX.y) / PHOTO_BOX.size;
      let luminance = 0;
      if (u >= 0 && u < 1 && v >= 0 && v < 1) {
        luminance = data[Math.floor(v * SAMPLE) * SAMPLE + Math.floor(u * SAMPLE)] / 255;
      }
      const index = Math.min(TRACE_RAMP.length - 1, Math.floor(luminance ** 1.4 * TRACE_RAMP.length));
      line += TRACE_RAMP[index];
    }
    rows.push(line.trimEnd());
  }
  return rows;
}

async function main() {
  if (!fs.existsSync(PHOTO_FILE)) throw new Error(`Missing ${PHOTO_FILE}`);
  const map = buildDisplacementMap();
  const trace = await buildTrace();
  const outFile = path.join(process.cwd(), 'src', 'app', 'ui', 'homePortraitAssets.ts');
  fs.writeFileSync(
    outFile,
    [
      '// Generated by scripts/generate-home-portrait-assets.ts. Do not edit by hand.',
      `// Source photo: public/ParhamBehzad-display.jpg (${PHOTO_SOURCE_SIZE} × ${PHOTO_SOURCE_SIZE}).`,
      '',
      `export const HOME_PORTRAIT_RIM_MAP = '${map}';`,
      '',
      `export const HOME_PORTRAIT_TRACE = ${JSON.stringify(trace.join('\n'))};`,
      '',
    ].join('\n'),
  );
  console.log(`Wrote ${path.relative(process.cwd(), outFile)} (map ${map.length} characters, trace ${trace.join('').length} glyphs).`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
