/**
 * Generates the static displacement map for the menu control's glass droplet.
 *
 * npm run generate:menu-droplet
 *
 * The map is a square PNG in which red and green encode the horizontal and
 * vertical sample offset (0.5 = none). Offsets point inward within an edge
 * band, so content passing under the rim is magnified toward the centre, as
 * through a thick droplet; the centre stays undistorted. The output is a
 * small TypeScript module holding a data URI, so no runtime work is needed.
 */

import fs from 'fs';
import path from 'path';
import zlib from 'zlib';

const SIZE = 64;
// Fraction of the radius where refraction begins; the band runs to the rim.
const BAND_START = 0.5;
const BAND_EXPONENT = 1.6;

function crc32(buffer: Buffer): number {
  let crc = 0xffffffff;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) {
      crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Buffer): Buffer {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

function encodePng(width: number, height: number, rgb: Uint8Array): Buffer {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8; // bit depth
  header[9] = 2; // colour type: RGB
  const rows = Buffer.alloc(height * (width * 3 + 1));
  for (let y = 0; y < height; y++) {
    rows[y * (width * 3 + 1)] = 0; // filter: none
    Buffer.from(rgb.buffer, y * width * 3, width * 3).copy(rows, y * (width * 3 + 1) + 1);
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', zlib.deflateSync(rows, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

const pixels = new Uint8Array(SIZE * SIZE * 3);
for (let y = 0; y < SIZE; y++) {
  for (let x = 0; x < SIZE; x++) {
    const u = ((x + 0.5) / SIZE) * 2 - 1;
    const v = ((y + 0.5) / SIZE) * 2 - 1;
    const r = Math.hypot(u, v);
    const band = r >= 1 ? 0 : Math.max(0, (r - BAND_START) / (1 - BAND_START)) ** BAND_EXPONENT;
    // Unit vector toward the centre, scaled by the band strength.
    const dx = r === 0 ? 0 : (-u / r) * band;
    const dy = r === 0 ? 0 : (-v / r) * band;
    const i = (y * SIZE + x) * 3;
    pixels[i] = Math.round((0.5 + dx * 0.5) * 255);
    pixels[i + 1] = Math.round((0.5 + dy * 0.5) * 255);
    pixels[i + 2] = 128;
  }
}

const dataUri = `data:image/png;base64,${encodePng(SIZE, SIZE, pixels).toString('base64')}`;
const outFile = path.join(process.cwd(), 'src', 'app', 'ui', 'menuDropletMap.ts');
fs.writeFileSync(
  outFile,
  `// Generated by scripts/generate-menu-droplet-map.ts. Do not edit by hand.\nexport const MENU_DROPLET_MAP = '${dataUri}';\n`,
);
console.log(`Wrote ${path.relative(process.cwd(), outFile)} (${dataUri.length} characters).`);
